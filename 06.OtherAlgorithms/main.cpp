#include <iostream>
#include <string>
#include <vector>
#include <algorithm>
#include <numeric>
#include <functional>
#include <iterator>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                     Огляд інших алгоритмів і засобів (для самостійного перегляду)
==========================================================================================================================================

  На парі ми розібрали стандартні функтори, лямбди і найуживаніші алгоритми:
  sort, find, find_if, count_if, any_of / all_of, max_element / min_element, accumulate, for_each, transform, erase_if.
  Тут коротко показано інші корисні алгоритми і засоби: що це і навіщо. Кожен приклад — кілька рядків у main.
*/

void print(const vector<int>& values)
{
    for (int value : values)
    {
        cout << value << " ";
    }
    cout << endl;
}

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // =====================================================================================================================
    // reverse — розвертає діапазон задом наперед.
    // Навіщо: вивести історію від нових записів до старих, перевернути рядок.
    cout << "--- reverse ---" << endl;
    vector<int> history = { 1, 2, 3, 4, 5 };
    reverse(history.begin(), history.end());
    print(history);                                             // 5 4 3 2 1
    string word = "stressed";
    reverse(word.begin(), word.end());                          // string — теж контейнер: desserts
    cout << word << endl;
    // Увага: український текст так не розвернути — у UTF-8 літера займає кілька байтів, і reverse їх переплутає.

    // =====================================================================================================================
    // unique — прибирає ПОРУЧ розташовані повтори (тому перед ним сортують). Як і remove_if, сам нічого не видаляє,
    // а повертає ітератор на новий «кінець» — після нього викликають erase.
    // Навіщо: отримати список без повторів, зберігши vector (альтернатива — set).
    cout << "--- sort + unique ---" << endl;
    vector<int> ids = { 5, 3, 5, 1, 3, 3 };
    sort(ids.begin(), ids.end());                               // 1 3 3 3 5 5
    ids.erase(unique(ids.begin(), ids.end()), ids.end());       // 1 3 5
    print(ids);

    // =====================================================================================================================
    // binary_search — швидкий бінарний пошук у ВІДСОРТОВАНОМУ діапазоні; повертає bool.
    // Навіщо: часті перевірки «чи є елемент» у великому відсортованому векторі.
    cout << "--- binary_search ---" << endl;
    cout << "Є 3? " << binary_search(ids.begin(), ids.end(), 3) << endl;   // 1

    // =====================================================================================================================
    // fill — заповнює діапазон одним значенням; iota (з <numeric>) — послідовними значеннями.
    // Навіщо: скинути масив у початковий стан, пронумерувати місця.
    cout << "--- fill, iota ---" << endl;
    vector<int> seats(5);
    iota(seats.begin(), seats.end(), 1);                        // 1 2 3 4 5
    print(seats);
    fill(seats.begin(), seats.end(), 0);                        // 0 0 0 0 0
    print(seats);

    // =====================================================================================================================
    // copy_if — копіює в інший контейнер лише елементи, що задовольняють умову.
    // back_inserter (з <iterator>) сам робить push_back, тож розмір приймача готувати не треба.
    // Навіщо: відібрати частину даних, не змінюючи оригінал.
    cout << "--- copy_if ---" << endl;
    vector<int> scores = { 40, 95, 70, 88, 55 };
    vector<int> passed;
    copy_if(scores.begin(), scores.end(), back_inserter(passed), [](int s) { return s >= 60; });
    print(passed);                                              // 95 70 88

    // =====================================================================================================================
    // min, max, clamp — для двох значень і для обмеження значення діапазоном.
    // Навіщо: здоров'я не менше 0 і не більше максимуму, гучність у межах 0–100.
    cout << "--- min, max, clamp ---" << endl;
    int health = 130;
    cout << "Більше з 3 і 8: " << max(3, 8) << endl;
    cout << "Здоров'я в межах 0–100: " << clamp(health, 0, 100) << endl;   // 100

    // =====================================================================================================================
    // function (з <functional>) — обгортка, у яку можна покласти будь-що, що викликається: функцію, функтор, лямбду.
    // Навіщо: ЗБЕРЕГТИ поведінку в змінній або полі класу і викликати пізніше — обробники кнопок, реакції на події.
    cout << "--- function ---" << endl;
    function<void()> onClick = []() { cout << "Кнопку натиснуто" << endl; };
    if (onClick)                                                // порожню function викликати не можна
    {
        onClick();
    }

    // =====================================================================================================================
    // ranges (C++20) — версії алгоритмів, яким передають весь контейнер, а не begin() і end().
    // Навіщо: коротший і безпечніший запис; у нових проєктах трапляється дедалі частіше.
    cout << "--- ranges ---" << endl;
    vector<int> levels = { 7, 2, 9, 4 };
    ranges::sort(levels, greater<int>());
    print(levels);                                              // 9 7 4 2
    cout << "Рівнів понад 5: " << ranges::count_if(levels, [](int l) { return l > 5; }) << endl;

    return 0;
}
