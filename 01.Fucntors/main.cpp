using namespace std;

/*
==========================================================================================================================================
                                                        Стандартні функтори
==========================================================================================================================================

                                                        СТАНДАРТНІ ФУНКТОРИ
  ФУНКТОР — об'єкт, який можна викликати як функцію: у його класі перевантажено оператор виклику ().
  Бібліотека <functional> містить готові функтори для порівняння, арифметики та логічних операцій.
  Їх передають контейнерам і алгоритмам, щоб задати правило: як порівнювати елементи або яку операцію виконувати.
  За замовчуванням map, set і sort упорядковують елементи за допомогою less (за зростанням);
  функтор greater змінює порядок на спадання.

  ----------------------------------------------------------------------------------------------------------------------------------------

  Стандартні функтори (шаблонні класи; об'єкт створюють дужками: greater<int>()):
      порівняння:   less<T>  greater<T>  less_equal<T>  greater_equal<T>  equal_to<T>  not_equal_to<T>
      арифметика:   plus<T>  minus<T>  multiplies<T>  divides<T>  modulus<T>  negate<T>
      логіка:       logical_and<T>  logical_or<T>  logical_not<T>

  Де трапляються:
      map<int, string, greater<int>>                     ключі за спаданням
      set<int, greater<int>>                             значення за спаданням
      priority_queue<int, vector<int>, greater<int>>     першим виходить НАЙМЕНШИЙ елемент
      sort(v.begin(), v.end(), greater<int>())           сортування за спаданням (тема «Алгоритми»)
*/

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // ===================================== Основний синтаксис =====================================

    greater<int> isGreater;                              // об'єкт-функтор
    cout << "5 > 3? " << isGreater(5, 3) << endl;        // викликається як функція: 1
    plus<int> add;
    cout << "2 + 3 = " << add(2, 3) << endl;             // 5
    cout << "7 * 6 = " << multiplies<int>()(7, 6) << endl;   // створили і одразу викликали: 42

    // ============================================== Програма ==============================================

    cout << "--- Результати іспиту: map з greater ---" << endl;
    map<int, string, greater<int>> results;              // бали → студент, від найвищого
    results[87] = "Марія";
    results[95] = "Олена";
    results[72] = "Ігор";
    for (const pair<const int, string>& record : results)
    {
        cout << record.first << " — " << record.second << endl;
    }

    cout << "--- Різні оцінки: set з greater ---" << endl;
    set<int, greater<int>> grades = { 10, 7, 12, 7, 10, 9 };   // унікальні, від найвищої
    for (int grade : grades)
    {
        cout << grade << " ";
    }
    cout << endl;

    cout << "--- Дедлайни: priority_queue з greater ---" << endl;
    priority_queue<int, vector<int>, greater<int>> daysLeft;   // першим — найменше число днів
    daysLeft.push(14);
    daysLeft.push(3);
    daysLeft.push(7);
    while (!daysLeft.empty())
    {
        cout << "Завдання через " << daysLeft.top() << " дн." << endl;   // 3, 7, 14
        daysLeft.pop();
    }

    return 0;
}

